"""The Places payload: the picker's index, and the values small enough to ship.

Phase 0 measured the alternative. DuckDB-WASM is 6,295 KB over the wire, against
the 1,826 KB of JavaScript it would replace, so putting the engine in front of
first paint costs more than it saves. The warehouse stays the single source of
truth and the build emits a payload from it - the same relationship
census_series_index already has to the census panels.

What ships and what does not is decided by size, not by source:

  the index      every indicator Places can offer, 5,801 of them. Interned and
                 columnar it is about 1.4 MB raw and 50 KB gzipped, so the
                 picker can search everything with no engine at all.

  curated values one file per indicator group, fetched when something in that
                 group is first chosen. 70 groups, 1,560 values on average, the
                 largest 15,336. Shipping all 109,235 up front to show one
                 indicator would cost more than the file it replaces; a group
                 costs about 35 KB.

  census values  17 MB across two panels. They stay on Parquet and are read by
                 range request when a series is chosen, which is how the census
                 map already works.

  crop values    78,425 rows over three measures. Same treatment - the index
                 lists them, the values are read on demand.

Interning matters more than it looks. The index's labels are built from a small
vocabulary - 740 indicator stems, 284 column headings, four localities, five
sexes - so storing the parts and rebuilding the label in the browser costs a
third of storing the labels themselves.

Usage:
  build_payload.py --warehouse <dir> --out-dir <app/data>
"""
import argparse, json, pathlib, re

HERE_PLACES = pathlib.Path(__file__).resolve().parent

import duckdb


def safe(name):
    """A group key as a file name: the keys are already tame, but not trusted."""
    return re.sub(r'[^A-Za-z0-9_-]', '_', name)


def js_name(name):
    return re.sub(r'[^A-Za-z0-9_]', '_', name)


def intern(values):
    """[v0, v1, ...], [index per row] - the vocabulary and the pointers."""
    seen, vocab, idx = {}, [], []
    for v in values:
        if v not in seen:
            seen[v] = len(vocab)
            vocab.append(v)
        idx.append(seen[v])
    return {'v': vocab, 'i': idx}


def columnar(rows, names, interned):
    cols = list(zip(*rows)) if rows else [[] for _ in names]
    return {n: (intern(list(c)) if n in interned else list(c))
            for n, c in zip(names, cols)}


def write(path, global_name, obj, what):
    body = json.dumps(obj, separators=(',', ':'), ensure_ascii=False)
    path.write_text(
        f'/* Data Darbar - {what}. Generated by etl/places/build_payload.py;\n'
        f'   do not edit by hand. */\n'
        f'window.{global_name}={body};\n')
    return path.stat().st_size


# A merged key is "2017=<cell>" or "2017:female=<cell>", parts joined by \x1f.
# Recognised by that year prefix, never by the presence of "=": census table
# 12 publishes "Literate >=10", and ">=" is not a merge.
MERGED = re.compile(r'^((?:19|20)\d\d)(?::([a-z]+))?=')


def cells(ind):
    """The cells a key names: itself, or each part of a merged key."""
    ind = str(ind)
    if not MERGED.match(ind):
        return None
    return [p[MERGED.match(p).end():] for p in ind.split('\u001f') if MERGED.match(p)]


# ── what each topic opens on, and what it features ────────────────────────
# A topic opened on whichever of its rows sorted first. Education opened on
# "% Below Primary" and the whole map opened on the 0-4 age band, because the
# one rule that picked the national opener matched an indicator key that a
# later merge had rewritten, and nothing noticed. So the first entry of each
# list is the topic's opening view, chosen for a clear definition, broad
# coverage and a unit a reader recognises; the rest are the few measures most
# people come for. "Featured" is presentation order only - every other measure
# stays in the topic's full library.
#
# Keys are group_key|indicator. A merged indicator is matched through any of
# the cells it absorbed, and the build fails if a key resolves nowhere, so a
# rename upstream breaks the build rather than the opening map.
#
# Where the best rate is a partial survey it is used anyway, because a count
# of households mostly redraws the population map: the electricity and pucca
