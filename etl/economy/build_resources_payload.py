"""Economy payload for land and resources: mining, crop prices, emissions.

    build_resources_payload.py --warehouse app/data/warehouse --out app/data/resources_data.js

Writes window.DD_RESOURCES = {series, meta} in money_data.js's shape, so
money.js draws these with the same multi-line charts, chips, CSV and Real
toggle as the State Bank series: each series is [[date, value], ...].

  min_*  mineral extraction as an index, 2000-01 = 100, dated at the end of
         the fiscal year. Each mineral is printed in its own unit, so the
         index is what lets several share an axis; the levels and units are
         in meta and in the mineral_extraction table.
  cp_*   wholesale price, rupees per 40 kg, nominal, by month, in the market
         with the longest record for that crop.
  em_*   greenhouse gas emissions by sector, Mt CO2e (AR5), PakEmis.
"""
import argparse, json, pathlib

import duckdb

MINERALS = {'coal': 'Coal', 'natural_gas': 'Natural gas', 'crude_oil': 'Crude oil',
            'limestone': 'Limestone', 'rock_salt': 'Rock salt', 'gypsum_anhydrite': 'Gypsum',
            'chromite': 'Chromite', 'baryte': 'Baryte'}
BASE = '2000-01'
# crop, variety, market: the longest-running market for each
CROPS = {'cp_wheat': ('Wheat', 'Not specified', 'Lahore', 'Wheat, Lahore'),
         'cp_basmati': ('Rice', 'Basmati (Super Quality)', 'Multan', 'Basmati rice, Multan'),
         'cp_irri6': ('Rice', 'Irri-6', 'Sukkur', 'Irri-6 rice, Sukkur'),
         'cp_maize': ('Maize', 'Not specified', 'Lahore', 'Maize, Lahore')}
SECTORS = {'agriculture': 'Agriculture', 'power': 'Power', 'industry': 'Industry (energy)',
           'transport': 'Road transport', 'waste': 'Waste', 'ippu': 'Industrial processes',
           'fugitives': 'Fugitive (oil and gas)', 'residential': 'Homes and businesses',
           'aviation': 'Aviation', 'railways': 'Railways'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--warehouse', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    W = pathlib.Path(a.warehouse).as_posix()
    con = duckdb.connect()
    series, meta = {}, {}

    for m, label in MINERALS.items():
        rows = con.sql(f"""SELECT fiscal_year, value, unit FROM '{W}/mineral_extraction.parquet'
                           WHERE mineral = '{m}' AND value IS NOT NULL ORDER BY fiscal_year""").fetchall()
        base = next(v for fy, v, _ in rows if fy == BASE)
        assert base, f'{m}: no {BASE} base'
        series['min_' + m] = [[f'{int(fy[:4]) + 1}-06-30', round(100 * v / base, 1)] for fy, v, _ in rows]
        meta['min_' + m] = {'label': label, 'unit': rows[0][2], 'base': BASE,
                            'levels': [[fy, v] for fy, v, _ in rows]}

    for k, (crop, variety, market, label) in CROPS.items():
        rows = con.sql(f"""SELECT strftime(date, '%Y-%m-%d'), price_pkr_per_40kg
                           FROM '{W}/crop_prices_wholesale.parquet'
                           WHERE crop = '{crop}' AND variety = '{variety}' AND market = '{market}'
                             AND price_pkr_per_40kg IS NOT NULL ORDER BY date""").fetchall()
        assert len(rows) > 100, f'{k}: {len(rows)} months'
        series[k] = [[d, v] for d, v in rows]
        meta[k] = {'label': label, 'unit': 'Rs per 40 kg', 'freq': 'Monthly'}

    for s, label in SECTORS.items():
        rows = con.sql(f"""SELECT fiscal_end_year, round(co2e_Mt_AR5, 2)
                           FROM '{W}/emissions_national_sector.parquet'
                           WHERE row_kind = 'sector' AND sector = '{s}'
                           ORDER BY fiscal_end_year""").fetchall()
        series['em_' + s] = [[f'{y}-06-30', v] for y, v in rows]
        meta['em_' + s] = {'label': label, 'unit': 'Mt CO2e (AR5)', 'freq': 'Annual'}
    total = con.sql(f"""SELECT fiscal_end_year, co2e_Mt_AR5 FROM '{W}/emissions_national_sector.parquet'
                        WHERE row_kind = 'covered_total' ORDER BY 1""").fetchall()
    # the sectors must add to PakEmis's own covered total
    for y, t in total:
        got = sum(v for k in SECTORS for d, v in series['em_' + k] if d.startswith(str(y)))
        assert abs(got - t) < 0.5, f'emissions {y}: sectors {got:.1f} against total {t:.1f}'

    out = pathlib.Path(a.out)
    out.write_text('/* Data Darbar - land and resources payload. Generated by\n'
                   '   etl/economy/build_resources_payload.py; do not edit by hand. */\n'
                   'window.DD_RESOURCES=' + json.dumps({'series': series, 'meta': meta},
                                                       separators=(',', ':')) + ';\n')
    for k, v in series.items():
        print(f'  {k:22s} {len(v):>4} points  {v[0][0]} to {v[-1][0]}')
    print(f'  -> {out} ({out.stat().st_size / 1e3:.1f} KB)')


if __name__ == '__main__':
    main()
